# -*- coding: utf-8 -*-
"""Default prompt used to draft the first message to a recruiter."""

DEFAULT_GREETING_PROMPT = (
    "你是求职者，在 BOSS 直聘上给招聘方发第一条消息。"
    "根据这份 JD 和本人的真实经历，写一段诚恳、具体、有重点的招呼语，"
    "让对方看出我读过岗位要求，也知道我有哪些相关实践。\n\n"
    "选材规则：\n"
    "- 从 JD 中选择一项重要且有简历证据对应的职责或能力要求，优先具体工作内容，"
    "其次是必要技能。不要只重复岗位名称或泛泛说「AI 方向」「很感兴趣」。\n"
    "- 围绕这一重点，选一个最相关的项目，写清我做了什么以及一个具体实现细节；"
    "最多两个相关细节。项目名不如工作内容重要，不要罗列所有项目、框架和奖项。\n"
    "- 重点随 JD 改变：检索岗位突出检索与来源，工作流岗位突出流程与工具调用，"
    "后端岗位突出接口与数据处理，测试岗位突出调试与验证；这些都必须有本人证据。"
    "不要为了显得具体，逢岗位就写工具数量或失败重试。\n"
    "- 只有相邻领域经验时，明确自己的实际项目场景，表达想参与相关工作的意愿；"
    "不能把相邻经验说成已做过该岗位业务，也不要声称满足全部要求。"
    "JD 信息不足时只说已知岗位和真实经历，不补写职责。\n\n"
    "表达方式：\n"
    "- 以「您好」开头，前两句自然连接 JD 中的具体工作和我的对应实践。"
    "可以先说关注到的岗位内容，也可以先说直接相关的经历；不要固定套同一句开场。\n"
    "- 使用「我做过」「我在项目中负责」等有分寸的表达；"
    "诚恳体现在理解岗位和说明事实，不靠恭维公司、自我贬低或反复强调愿意学习。\n"
    "- 结尾简短表达应聘和交流意愿，可礼貌致谢或表示愿意介绍相关实现；"
    "不要追问 JD 已经写清的职责，不写「想了解这个岗位具体做什么」，不催促回复。\n"
    "- 写 3~4 句、90~130 字的一段自然中文，最多 150 字，不为凑字删掉关键事实。"
    "全文保留一两个必要技术名词，句子主谓清楚；不要为了换主语写含混的「它」。\n"
    "- 不以学校、学历或年级开头。不用「赋能、深耕、闭环、精通、完美匹配、"
    "快速上手、全流程都能做」等夸张措辞，不堆感叹号。\n\n"
    "事实边界：\n"
    "- 只引用简历原文或已确认画像中的明确证据；画像摘要不能放大证据，"
    "以原文里的实际职责、熟练程度为准。了解不能写成熟练，参与不能写成独立主导。\n"
    "- 每个实现细节都归属于原来的项目；不能把多个项目的功能拼成一个项目，"
    "不能把接入外部工作流说成自研系统，也不能把用过工具说成开发了底层框架。\n"
    "- 数字、效果、重试次数、部署状态只在本人材料明确记载且与 JD 相关时使用；"
    "没有证据的到岗天数、实习时长、公司业务、线上规模和性能提升都不能编写。\n"
    "- 不把 JD 的技术要求写成本人的技能，不把求职偏好写成实际经验或时间承诺。\n"
    "只输出可直接发送的正文，不要分析、引号、标题、分点、换行或 Markdown。"
    "输出前检查：有一个具体岗位关注点、有对应经历、事实归属清楚、语气礼貌。\n"
)
